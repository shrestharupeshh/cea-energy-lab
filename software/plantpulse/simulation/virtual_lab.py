"""Virtual laboratory (Phase 6): a simulated experimental environment that exercises the complete
software stack - recipes, safety envelope, node protocol and control logic, sensor frames, raw
storage, calibration, QC, imaging, vision traits, manual-measurement records, harvest records -
with a hidden "true" plant model that deliberately differs from the digital twin's defaults.

PURPOSE: software verification and analysis-pipeline rehearsal (the SAP can be run end to end
before any plant is grown). NOT a source of scientific results. Every experiment created here
has data_class = 'simulated', and exported bundles carry a warning banner.
"""
from __future__ import annotations

import json
from dataclasses import dataclass, field
from datetime import datetime, timedelta, timezone
from pathlib import Path

import cv2
import numpy as np
import pandas as pd

from ..acquisition import node_logic as nlg
from ..acquisition.safety import Envelope, check_setpoints, to_node_command
from ..acquisition.sim_node import SimNode
from ..computer_vision import pipeline as cvp
from ..data import naming
from ..data.db import MetaDB
from ..data.pipeline import daily_summary, process_sensors
from ..data.store import Store, sha256_file
from ..digital_twin import crop as cropm
from .synth_images import PlantLook, render_station

CONTROL = {"ppfd": 250.0, "photoperiod_h": 16.0, "air_t_day": 23.0, "air_t_night": 20.0, "rh": 68.0, "ec": 1.4}
TREATMENTS = {
    "C": {"description": "Control", "recipe": CONTROL},
    "L": {"description": "Reduced light, PPFD 125", "recipe": {**CONTROL, "ppfd": 125.0}},
    "H": {"description": "Elevated temperature 30/26 C", "recipe": {**CONTROL, "air_t_day": 30.0, "air_t_night": 26.0, "rh": 76.0}},
    "N": {"description": "Reduced nutrients, EC 0.4", "recipe": {**CONTROL, "ec": 0.4}},
}


@dataclass
class TruthConfig:
    """Hidden data-generating process. Differs from CropParams() defaults on purpose."""
    crop: cropm.CropParams = field(default_factory=lambda: cropm.CropParams(c_eps=15.3e-6, c_gr_max=5.6e-6, t_opt_high=27.0, sla_obs=0.032, ec_half=0.32))
    cv_run: float = 0.08
    cv_pod: float = 0.04
    cv_unit: float = 0.06
    cv_plant: float = 0.14
    cv_plant_daily: float = 0.02
    manual_diameter_sd_mm: float = 4.0
    pod_room_offset_c: tuple = (0.0, 0.3, -0.2, 0.4)      # e.g. upper tier slightly warmer


def projected_area_cm2(leaf_area_cm2: float) -> float:
    """Assumed mapping from total leaf area to top-view projected area (self-shading saturates it)."""
    return 0.68 * leaf_area_cm2 / (1.0 + leaf_area_cm2 / 1100.0)


def run_virtual_experiment(root: str | Path, experiment_id: str, allocation: dict[int, str], *, days: int = 28, onset_day: int = 10,
                           seed: int = 0, run_effect: float | None = None, truth: TruthConfig | None = None, study: str = "A",
                           image_every_days: int = 1, image_width: int = 760, dt_s: float = 60.0, images: bool = True,
                           day0: datetime | None = None, db: MetaDB | None = None, progress=None,
                           serial_harvest: dict[int, int] | None = None) -> dict:
    """Simulate one run (all pods in `allocation`: pod -> treatment code). Returns paths and tables."""
    truth = truth or TruthConfig()
    rng = np.random.default_rng(seed)
    root = Path(root)
    store = Store(root)
    own_db = db is None
    db = db or MetaDB(root / "plantpulse_meta.db")
    day0 = day0 or datetime(2027, 1, 4, 6, 0, tzinfo=timezone.utc)       # lights-on of day 0 (local = UTC in the simulation)
    db.create_experiment(experiment_id, study, f"VIRTUAL run {experiment_id}", "simulated", day0_utc=day0.strftime("%Y-%m-%dT%H:%M:%SZ"),
                         randomization_seed=seed, notes="Generated by plantpulse.simulation.virtual_lab; not experimental data.")
    for code in sorted(set(allocation.values())):
        db.add_treatment(experiment_id, code, TREATMENTS[code]["description"], TREATMENTS[code]["recipe"], onset_day if code != "C" else 0)
    db.assign_units(experiment_id, allocation, seed=seed)
    run_eff = float(np.exp(rng.normal(0, truth.cv_run))) if run_effect is None else run_effect
    env = Envelope()
    height = int(round(image_width * 0.75))
    mm_px = 524.0 / image_width
    truth_rows, trait_rows, frames_all = [], [], {}
    for pod, code in sorted(allocation.items()):
        unit = naming.unit_id(experiment_id, pod)
        unit_eff = run_eff * float(np.exp(rng.normal(0, truth.cv_pod) * 0 + rng.normal(0, truth.cv_unit)))
        node = SimNode(pod=pod, seed=seed * 100 + pod, crop=truth.crop, growth_multiplier=unit_eff,
                       room_t=20.0 + truth.pod_room_offset_c[(pod - 1) % 4])
        # sensors and calibrations for this pod (the pipeline must recover engineering units from raw counts)
        for kind, qty, unit_, coeffs in (
                ("par", "ppfd", "umol m-2 s-1", {"type": "linear", "gain": 1 / node.par_counts_per_umol, "offset": 0.0}),
                ("loadcell", "reservoir_mass", "g", {"type": "two_point", "raw0": node.res_zero_counts, "raw_ref": node.res_zero_counts + 1000 * node.res_counts_per_g, "ref": 1000.0}),
                ("air_t", "air_temperature", "C", {"type": "linear", "gain": 1.0, "offset": 0.0})):
            sid = f"SIM-P{pod:02d}-{kind}"
            db.add_sensor(sid, pod, kind, qty, unit_, model="simulated")
            if not len(db.q("SELECT 1 FROM calibration WHERE sensor_id=?", (sid,))):
                db.add_calibration(sid, coeffs, "simulated reference", valid_from_utc="2026-01-01T00:00:00Z", u_standard=0.0)
        db.x("INSERT OR IGNORE INTO camera (camera_id, pod, model, lens, settings_json) VALUES (?,?,?,?,?)",
             (f"SIM-CAM-P{pod:02d}", pod, "synthetic renderer", "n/a", json.dumps({"width": image_width, "height": height, "mm_per_px": mm_px})))
        plant_eff = np.exp(rng.normal(0, truth.cv_plant, 6))
        current = None
        harvested: set[int] = set()

        def apply(recipe: dict, source="recipe"):
            nonlocal current
            ok, sp, why = check_setpoints({k: v for k, v in recipe.items() if k != "ec"}, current, env, source)
            cmd = to_node_command(sp, node.env.ppfd_full) if ok else ""
            db.log_setpoint(unit, source, cmd or json.dumps(recipe), ok, "; ".join(why))
            if ok:
                node.write(cmd)
                current = sp
                node.ec_ms = recipe.get("ec", node.ec_ms)
            return ok

        node.write(f"TIME epoch={int(day0.timestamp())}")
        apply(CONTROL)
        node.write("MODE AUTO")
        node.readlines()
        frames = []
        steps_per_day = int(86400 / dt_s)
        for day in range(days):
            if day == onset_day and code != "C":
                apply(TREATMENTS[code]["recipe"])
                db.add_intervention(unit, "treatment_onset", TREATMENTS[code]["description"], utc=(day0 + timedelta(days=day)).strftime("%Y-%m-%dT%H:%M:%SZ"))
            if day == onset_day:      # every unit gets a solution exchange (sham for controls)
                db.add_intervention(unit, "solution_exchange", f"EC {node.ec_ms}", 28.0, "L", utc=(day0 + timedelta(days=day)).strftime("%Y-%m-%dT%H:%M:%SZ"))
            for k in range(steps_per_day):
                node.write("PING")
                f = node.step(dt_s, emit=False)
                f["utc"] = day0 + timedelta(seconds=day * 86400 + k * dt_s)
                frames.append(f)
                if node.reservoir_g < 800:                      # operator refills the top-up reservoir
                    node.reservoir_g = 5000.0
                    db.add_intervention(unit, "reservoir_refill", "", 5000.0, "g", utc=f["utc"].strftime("%Y-%m-%dT%H:%M:%SZ"))
                if k == int(6 * 3600 / dt_s):                   # noon: record truth, take images
                    tr = node.truth()
                    stress_days = max(day - onset_day, 0) if code != "C" else 0
                    looks = {}
                    for pos in range(1, 7):
                        if pos in harvested:
                            looks[pos] = PlantLook(0.0)
                            continue
                        eff = plant_eff[pos - 1] * float(np.exp(rng.normal(0, truth.cv_plant_daily)))
                        la, dw = tr["leaf_area_cm2"] * eff, tr["shoot_dw_g"] * eff
                        pa = projected_area_cm2(la)
                        look = PlantLook(pa, seed=seed * 1000 + pod * 10 + pos,
                                         chlorosis=min(0.06 * stress_days, 0.7) if code == "N" else 0.0,
                                         tipburn=min(0.05 * stress_days, 0.6) if code == "H" else 0.0,
                                         compact=min(0.04 * stress_days, 0.5) if code == "H" else (0.0 if code != "L" else -0.0))
                        looks[pos] = look
                        truth_rows.append({"experiment_id": experiment_id, "unit_id": unit, "plant_id": naming.plant_id(experiment_id, pod, pos),
                                           "pod": pod, "position": pos, "day": day, "treatment": code, "true_leaf_area_cm2": la,
                                           "true_shoot_dw_g": dw, "true_shoot_fw_g": dw / truth.crop.dm_content, "true_projected_area_cm2": pa,
                                           "unit_effect": unit_eff, "plant_effect": plant_eff[pos - 1]})
                    if serial_harvest and day in serial_harvest:          # Study-B style serial destructive harvest (after imaging)
                        pending_harvest = serial_harvest[day]
                    else:
                        pending_harvest = None
                    if images and day % image_every_days == 0:
                        for st in (1, 2, 3):
                            node.write(f"MOVE station={st}")
                            node.write("CAPTURE")
                            ts = f["utc"] + timedelta(seconds=10 * st)
                            dx = float(rng.normal(0, 0.08))                 # gantry repeatability
                            img, tmasks = render_station(looks, st, image_width, height, dx_mm=dx, seed=int(rng.integers(1 << 30)))
                            iid = naming.image_id(experiment_id, pod, st, ts)
                            rel = naming.image_relpath(iid)
                            path = store.image_path(rel)
                            path.parent.mkdir(parents=True, exist_ok=True)
                            cv2.imwrite(str(path), img)
                            db.add_image(iid, experiment_id, unit, st, ts.strftime("%Y-%m-%dT%H:%M:%SZ"), rel, sha256_file(path),
                                         camera_id=f"SIM-CAM-P{pod:02d}", gantry_steps=node.gpos, session="scheduled")
                            for rec in cvp.process_image(img, st, mm_px):
                                rec.update(image_id=iid, experiment_id=experiment_id, unit_id=unit, pod=pod, t_day=day + 0.25,
                                           plant_id=naming.plant_id(experiment_id, pod, rec["position"]), utc=ts,
                                           true_visible_area_cm2=tmasks[rec["position"]]["area_cm2"])
                                trait_rows.append(rec)
                        node.write("MOVE station=0")
                    if pending_harvest:
                        pos = pending_harvest
                        pid = naming.plant_id(experiment_id, pod, pos)
                        dw = tr["shoot_dw_g"] * plant_eff[pos - 1]
                        for q_, v_, u_ in (("shoot_fresh_mass", dw / truth.crop.dm_content, "g"), ("shoot_dry_mass", dw, "g"),
                                           ("leaf_area", tr["leaf_area_cm2"] * plant_eff[pos - 1], "cm2")):
                            db.add_manual(pid, q_, float(v_ * np.exp(rng.normal(0, 0.02))), u_, day=day, destructive=True, operator="SIM",
                                          measured_utc=f["utc"].strftime("%Y-%m-%dT%H:%M:%SZ"), instrument="balance/scanner")
                        db.x("UPDATE plant SET status='harvested', harvest_day=? WHERE plant_id=?", (day, pid))
                        harvested.add(pos)
                    if day in (0, 3, 7, 10, 14, 17, 21, 24) or day == days - 1:      # manual non-destructive session
                        for pos in sorted(set(range(1, 7)) - harvested):
                            pid = naming.plant_id(experiment_id, pod, pos)
                            d_true = 2 * np.sqrt(looks[pos].area_cm2 * 100 / np.pi) * 1.25
                            db.add_manual(pid, "diameter_max", float(d_true + rng.normal(0, truth.manual_diameter_sd_mm)), "mm", day=day,
                                          measured_utc=f["utc"].strftime("%Y-%m-%dT%H:%M:%SZ"), operator="SIM", instrument="ruler")
            if progress:
                progress(pod, day)
        node.readlines()
        # destructive harvest on the last day
        tr = node.truth()
        hutc = (day0 + timedelta(days=days)).strftime("%Y-%m-%dT%H:%M:%SZ")
        for pos in sorted(set(range(1, 7)) - harvested):
            pid = naming.plant_id(experiment_id, pod, pos)
            dw = tr["shoot_dw_g"] * plant_eff[pos - 1] * float(np.exp(rng.normal(0, 0.01)))
            dmc = truth.crop.dm_content * (1.25 if code == "L" and False else 1.0) * float(np.exp(rng.normal(0, 0.04)))
            for q, v, u in (("shoot_fresh_mass", dw / dmc, "g"), ("shoot_dry_mass", dw, "g"),
                            ("leaf_area", tr["leaf_area_cm2"] * plant_eff[pos - 1] * float(np.exp(rng.normal(0, 0.02))), "cm2")):
                db.add_manual(pid, q, float(v), u, measured_utc=hutc, day=days, destructive=True, operator="SIM", instrument="balance/scanner")
            db.x("UPDATE plant SET status='harvested', harvest_day=? WHERE plant_id=?", (days, pid))
        df = pd.DataFrame(frames)
        df["pod"] = pod
        store.append_raw(experiment_id, pod, df)
        frames_all[pod] = len(df)
    db.x("UPDATE experiment SET status='complete', end_utc=? WHERE experiment_id=?", ((day0 + timedelta(days=days)).strftime("%Y-%m-%dT%H:%M:%SZ"), experiment_id))
    minute = process_sensors(db, store, experiment_id)
    daily = daily_summary(db, minute, experiment_id)
    store.write_processed(experiment_id, "daily_env", daily)
    traits = pd.DataFrame(trait_rows)
    if len(traits):
        store.write_processed(experiment_id, "traits", traits)
    truth_df = pd.DataFrame(truth_rows)
    tdir = root / "simulation_truth"
    tdir.mkdir(parents=True, exist_ok=True)
    truth_df.to_parquet(tdir / f"{experiment_id}_truth.parquet", index=False)
    if own_db:
        db.close()
    return {"experiment_id": experiment_id, "minute": minute, "daily": daily, "traits": traits, "truth": truth_df, "frames": frames_all,
            "run_effect": run_eff}
