"""Run all engineering calculations and write the calculation report + PPFD map figure."""
from __future__ import annotations

from pathlib import Path

from ..config import REPO_ROOT, load_design
from . import electrical, hydraulics, imaging, lighting, structural, thermal


def run_all(d: dict | None = None) -> dict:
    d = d or load_design()
    lt = lighting.analyse(d)
    st = structural.analyse(d)
    hy = hydraulics.analyse(d, st.water_volume_l)
    ppf_in = lt.ppf_total_umol_s * d["pod"]["window_par_transmittance"]
    th = thermal.analyse(d, lt.electrical_w_full, ppf_in)
    im = imaging.analyse(d)
    el = electrical.analyse(d, lt.electrical_w_full, lt.electrical_w_nominal)
    return {"lighting": lt, "structural": st, "hydraulics": hy, "thermal": th, "imaging": im, "electrical": el}


def _table(rows) -> str:
    out = ["| Quantity | Value | Note |", "|---|---|---|"]
    out += [f"| {a} | {b} | {c} |" for a, b, c in rows]
    return "\n".join(out)


def write_report(out_dir: Path | None = None) -> Path:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    d = load_design()
    r = run_all(d)
    out_dir = out_dir or REPO_ROOT / "hardware" / "mechanical" / "calculations"
    out_dir.mkdir(parents=True, exist_ok=True)
    lt = r["lighting"]
    fig, ax = plt.subplots(figsize=(7, 4.2))
    m = ax.pcolormesh(lt.xs, lt.ys, lt.ppfd_map, shading="auto", cmap="viridis")
    fig.colorbar(m, label="PPFD at lid plane, 100 % output (µmol m$^{-2}$ s$^{-1}$)")
    tub = d["tub"]
    x0, y0 = tub["tub_offset_x"], tub["tub_offset_y"]
    ax.add_patch(plt.Rectangle((x0, y0), tub["ext_l"], tub["ext_w"], fill=False, ec="w", lw=1.5))
    for py in tub["plant_rows_y"]:
        for px in tub["plant_cols_x"]:
            ax.plot(x0 + px, y0 + py, "wo", ms=5, mfc="none")
    ax.set(xlabel="x (mm)", ylabel="y (mm)", title="Simulated PPFD map (design estimate, not a measurement)", aspect="equal")
    fig.tight_layout()
    fig.savefig(out_dir / "ppfd_map_simulated.png", dpi=150)
    plt.close(fig)

    sections = [
        ("1. Structural loading and deflection", "structural"),
        ("2. Recirculation hydraulics", "hydraulics"),
        ("3. Lighting", "lighting"),
        ("4. Heat, moisture, CO2 and airflow", "thermal"),
        ("5. Imaging geometry and positioning accuracy", "imaging"),
        ("6. Electrical power", "electrical"),
    ]
    md = [
        "# Engineering calculation report",
        "",
        "Generated by `python -m plantpulse.engineering.report` from `hardware/design_parameters.yaml`.",
        "Do not edit by hand. Every value is a **design calculation**; none is a measurement.",
        "Inputs flagged `verify` in the parameter file must be confirmed against datasheets, and",
        "each result has a corresponding commissioning test in `docs/validation/validation_plan.md`.",
        "",
    ]
    for title, key in sections:
        md += [f"## {title}", "", _table(r[key].as_rows()), ""]
        if key == "lighting":
            md += ["![Simulated PPFD map](ppfd_map_simulated.png)", ""]
        if key == "electrical":
            md += ["### Load schedule (per pod)", "", "| Load | Rail | Peak W | Typ. duty | Mean W | Note |", "|---|---|---|---|---|---|"]
            md += [f"| {l.name} | {l.rail} | {l.peak_w:.1f} | {l.duty_typ:.3f} | {l.avg_w:.2f} | {l.note} |" for l in r["electrical"].loads]
            md += [""]
    md += [
        "## Method notes and limits",
        "",
        "- Beams: Euler-Bernoulli, joints idealised as pinned (conservative for deflection).",
        "- Hydraulics: Darcy-Weisbach with Haaland friction factor; generic quadratic pump curve.",
        "- Lighting: Lambertian point-source superposition with image-source wall reflections (2 bounces).",
        "  PPF is derived from luminous flux with a literature conversion factor; expect +/- 10 %.",
        "- Thermal: steady state, well-mixed chamber; fan curve linearised; light-trap loss coefficient estimated.",
        "- Imaging: thin-lens model; positioning budget is root-sum-square of independent contributions.",
        "",
    ]
    path = out_dir / "calculation_report.md"
    path.write_text("\n".join(md), encoding="utf-8")
    return path


if __name__ == "__main__":
    print(write_report())
