"""Phase 6 rehearsal: run a complete SIMULATED Study A (4 x 4 Latin square) through the whole stack
and execute the pre-specified analyses on it. Output: simulation/reports/virtual_study_report.md

    python simulation/run_virtual_study.py [--quick]

Everything produced here is simulated. The report is a software-verification document: it shows
that the acquisition, storage, QC, vision, statistics, ML and twin code run end to end and recover
effects that were deliberately planted. It contains no scientific finding.
"""
from __future__ import annotations

import sys
import time
import warnings
from pathlib import Path

import numpy as np
import pandas as pd

from plantpulse.config import REPO_ROOT
from plantpulse.computer_vision import evaluation as cveval
from plantpulse.computer_vision.pipeline import QC_TOUCHING, QC_TRUNCATED
from plantpulse.data.db import MetaDB
from plantpulse.data.export import export_dataset, verify_dataset
from plantpulse.data.store import Store
from plantpulse.digital_twin import calibration as cal
from plantpulse.digital_twin import crop as cropm
from plantpulse.digital_twin.hybrid import BASE_FEATURES, HybridModel, MechanisticModel, MLModel
from plantpulse.machine_learning import features as F
from plantpulse.machine_learning import metrics as M
from plantpulse.machine_learning import tasks
from plantpulse.simulation.virtual_lab import TREATMENTS, run_virtual_experiment
from plantpulse.stats.design import is_latin, latin_square
from plantpulse.stats.inference import cluster_bootstrap_diff, latin_square_anova, unit_means

warnings.filterwarnings("ignore")
QUICK = "--quick" in sys.argv
OUT = REPO_ROOT / "simulation" / "output" / ("lab_quick" if QUICK else "lab")
REPORT = REPO_ROOT / "simulation" / "reports" / ("virtual_study_report_quick.md" if QUICK else "virtual_study_report.md")
DAYS, ONSET = (12, 4) if QUICK else (28, 10)
SERIAL = {3: 2, 6: 4, 9: 6} if QUICK else {7: 2, 14: 4, 21: 6}
SEED = 20270104


def md_table(df: pd.DataFrame, floatfmt: str = "{:.3g}") -> str:
    cols = list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for _, r in df.iterrows():
        lines.append("| " + " | ".join(floatfmt.format(v) if isinstance(v, (float, np.floating)) else str(v) for v in r) + " |")
    return "\n".join(lines)


def main():
    t_start = time.time()
    import shutil
    reuse = "--reuse" in sys.argv and (OUT / "plantpulse_meta.db").exists()
    if OUT.exists() and not reuse:
        shutil.rmtree(OUT)
    if (OUT / "export").exists():
        shutil.rmtree(OUT / "export")
    square = latin_square(["C", "L", "H", "N"], seed=SEED)
    assert is_latin(square)
    db = MetaDB(OUT / "plantpulse_meta.db")
    exps = []
    for i, run in enumerate(square.index):
        exp = f"EXP-2027-VA{i + 1}"
        alloc = {j + 1: square.iloc[i, j] for j in range(4)}
        if not reuse:
            run_virtual_experiment(OUT, exp, alloc, days=DAYS, onset_day=ONSET, seed=SEED + i, db=db, serial_harvest=SERIAL)
            print(f"simulated {exp} {alloc}  ({time.time() - t_start:.0f} s)", flush=True)
        exps.append(exp)
    store = Store(OUT)
    traits = pd.concat([store.read_processed(e, "traits") for e in exps], ignore_index=True)
    daily_env = pd.concat([store.read_processed(e, "daily_env") for e in exps], ignore_index=True)
    minute = pd.concat([store.read_processed(e, "sensors_1min") for e in exps], ignore_index=True)
    truth = pd.concat([pd.read_parquet(OUT / "simulation_truth" / f"{e}_truth.parquet") for e in exps], ignore_index=True)
    meta = db.q("SELECT plant_id, unit_id, experiment_id, pod, treatment, onset_day FROM v_plant_full")
    manual = db.q("SELECT m.*, p.unit_id FROM manual_measurement m JOIN plant p USING (plant_id)")
    S = ["# Virtual Study A - software verification report", "",
         "> **SIMULATED DATA. This report verifies software and rehearses the analysis plan. It contains no experimental",
         "> result and nothing in it may be cited as a finding about plants.** The hidden data-generating model, its planted",
         "> treatment effects and its noise levels are in `plantpulse/simulation/virtual_lab.py`.", "",
         f"Generated by `simulation/run_virtual_study.py`{' --quick' if QUICK else ''}; {len(exps)} simulated runs x 4 pods x 6 plants, "
         f"{DAYS} days, treatment onset day {ONSET}, serial harvests on days {sorted(SERIAL)}.", "",
         "## 1. Design", "", "Randomised Latin square (rows = runs, columns = pods):", "", md_table(square.reset_index(names='run')), ""]

    # ---------------------------------------------------------------- 2. data completeness / QC
    comp = minute.groupby("unit_id").agg(minutes=("air_t", "size"), air_t_pass=("air_t_qc", lambda q: float((q == 0).mean())),
                                         ppfd_pass=("ppfd_qc", lambda q: float((q == 0).mean()))).reset_index()
    expected = DAYS * 1440
    S += ["## 2. Data completeness and QC", "",
          f"Sensor records per unit: min {comp.minutes.min()}, expected {expected} ({100 * comp.minutes.min() / expected:.1f} %). "
          f"Air-temperature records passing QC: {100 * comp.air_t_pass.min():.1f}-{100 * comp.air_t_pass.max():.1f} %. "
          f"Images: {db.q('SELECT COUNT(*) n FROM image').n[0]}; trait records: {len(traits)}; "
          f"fiducial registration succeeded on {100 * (traits.n_fiducials >= 2).mean():.1f} % of trait records "
          "(when it fails the pipeline falls back to the nominal gantry position and sets a QC flag).", ""]
    env_tab = daily_env.merge(meta.drop_duplicates("unit_id")[["unit_id", "treatment"]], on="unit_id")
    env_tab = env_tab[env_tab.day >= ONSET].groupby("treatment")[["air_t_light", "air_t_dark", "rh_mean", "ppfd_light", "dli", "ec_mean", "kwh_led", "kwh_act", "water_use_g"]].mean().reset_index()
    S += ["Mean achieved environment after treatment onset (simulated controller on the simulated pod):", "", md_table(env_tab), ""]

    # ---------------------------------------------------------------- 3. vision vs synthetic truth
    tr = traits.copy()
    tr["isolated"] = (tr.qc.astype(int) & (QC_TOUCHING | QC_TRUNCATED)) == 0
    tr = tr[tr.true_visible_area_cm2 > 0.5]
    agree = cveval.compare(tr, {"true_visible_area_cm2": "projected_area_cm2"}, group="isolated")
    agree["group"] = agree["group"].map({True: "isolated plants", False: "touching or truncated"})
    S += ["## 3. Vision pipeline against synthetic ground truth", "",
          "Projected area from the pipeline vs the renderer's exact visible area (synthetic images; says nothing about real leaves):", "",
          md_table(agree[["group", "n", "bias_pct", "loa_pct_of_mean", "mape", "ccc", "r2_identity"]]), "",
          f"Share of plant-images flagged touching/truncated by day: "
          + ", ".join(f"d{d}: {100 * (1 - g.isolated.mean()):.0f} %" for d, g in tr.groupby(np.floor(tr.t_day).astype(int)) if d % 4 == 0) + ".",
          "Once canopies touch, per-plant area is a geometric split; unit-level canopy cover remains valid.", ""]

    # ---------------------------------------------------------------- 4. Latin-square analysis of harvest dry mass
    final = manual[(manual.quantity == "shoot_dry_mass") & (manual.day == DAYS)].merge(meta, on=["plant_id", "unit_id"])
    units = unit_means(final.rename(columns={"experiment_id": "run"}), "value", keys=("run", "pod", "treatment"))
    res = latin_square_anova(units, "value", control="C")
    con = res["contrasts"].copy()
    con["ratio_ci_low"] = con.ratio_ci.map(lambda t: t[0])
    con["ratio_ci_high"] = con.ratio_ci.map(lambda t: t[1])
    planted = {}
    for code in "LHN":
        r_c = cropm.simulate_schedule(DAYS, 250, 16, 23, 20, ec=1.4, p=cropm.CropParams(c_eps=15.3e-6, c_gr_max=5.6e-6, t_opt_high=27.0, sla_obs=0.032, ec_half=0.32))
        rec = TREATMENTS[code]["recipe"]
        day = np.arange(DAYS)
        sw = lambda a, b: np.where(day >= ONSET, b, a)
        r_t = cropm.simulate_schedule(DAYS, sw(250, rec["ppfd"]), 16, sw(23, rec["air_t_day"]), sw(20, rec["air_t_night"]), ec=sw(1.4, rec["ec"]),
                                      p=cropm.CropParams(c_eps=15.3e-6, c_gr_max=5.6e-6, t_opt_high=27.0, sla_obs=0.032, ec_half=0.32))
        planted[code] = float(r_t["shoot_dw_g"][-1] / r_c["shoot_dw_g"][-1])
    con["planted_ratio_approx"] = con.treatment.map(planted)
    S += ["## 4. Pre-specified analysis: harvest shoot dry mass (SAP section 2)", "",
          f"Latin-square ANOVA on log pod-run means, {res['df_resid']} residual df, Dunnett critical value {res['dunnett_crit']:.2f}:", "",
          md_table(con[["treatment", "ratio", "ratio_ci_low", "ratio_ci_high", "significant", "planted_ratio_approx"]]), "",
          "`planted_ratio_approx` is the effect built into the simulator at nominal setpoints (no pod/run noise). The analysis code "
          "recovers the planted effects within its intervals, which is what this check is for.", ""]

    # ---------------------------------------------------------------- 5. feature tables
    pdt = F.plant_day_table(traits, daily_env, meta[["plant_id", "unit_id", "experiment_id", "treatment", "onset_day"]])
    for c in ("unit_id", "experiment_id"):
        if f"{c}_x" in pdt:
            pdt[c] = pdt[f"{c}_x"]
    unit_tab = F.unit_day_table(pdt)
    destr = manual[manual.destructive == 1].pivot_table(index=["plant_id", "day"], columns="quantity", values="value").reset_index()
    destr["img_day"] = np.minimum(destr.day, DAYS - 1)
    harvest_tab = destr.merge(pdt, left_on=["plant_id", "img_day"], right_on=["plant_id", "day"], suffixes=("_harvest", ""))

    # ---------------------------------------------------------------- 6. Model D biomass
    bsum, _ = tasks.biomass_models(harvest_tab, "shoot_dry_mass")
    S += ["## 5. Model D - biomass from non-destructive features (leave-one-run-out)", "",
          f"{len(harvest_tab)} destructively measured plants (serial + final harvests). MAPE with pod-run cluster-bootstrap 95 % CI:", "",
          md_table(bsum[["model", "n", "mape", "mape_ci_low", "mape_ci_high", "rmse", "bias", "r2"]]), ""]

    # ---------------------------------------------------------------- 7. Model A growth
    gsum, _ = tasks.growth_models(pdt, horizon_days=3)
    S += ["## 6. Model A - projected area 3 days ahead (leave-one-run-out)", "",
          md_table(gsum[["model", "n", "mape", "rmse", "bias", "r2"]]), "",
          "The persistence baseline is hard to beat at a 3-day horizon; a model that does not beat it has no forecasting value.", ""]

    # ---------------------------------------------------------------- 8. Models B/C/E stress
    S += ["## 7. Models B, C, E - stress classification and earliness (Study D rehearsal)", ""]
    for blind in (True, False):
        csum, cpred = tasks.stress_classification(unit_tab, blind=blind, model_names=("logistic", "random_forest", "gradient_boosting"))
        det = tasks.early_detection(cpred)
        dsum = tasks.summarize_detection(det, censor_day=DAYS - ONSET)
        label = "treatment-blind (response channels only)" if blind else "all environment channels (trivially sees the setpoint change)"
        S += [f"### Environment set: {label}", "", "Unit-day classification, out-of-fold:", "",
              md_table(csum[["features", "model", "n", "auroc", "auroc_ci_low", "auroc_ci_high", "brier"]]), "",
              "Alarm timing (threshold = no false alarm on the negative unit-days of the other runs; alarm = 2 consecutive days above it):", "",
              md_table(dsum), ""]
        if blind:
            best = {s: dsum[dsum.model.str.startswith(s + "|")].sort_values("median_delay_days").iloc[0] for s in ("ENV", "IMG", "ENV+IMG") if dsum.model.str.startswith(s + "|").any()}
            per_trt = det[det.model.isin([b.model for b in best.values()]) & (det.treatment != "C")].assign(delay=lambda d: d.delay_days.fillna(DAYS - ONSET)) \
                .pivot_table(index="treatment", columns="model", values="delay", aggfunc="median").reset_index()
            S += ["Median delay by treatment for the best model of each information set (days after onset; undetected = censored):", "", md_table(per_trt), ""]
    S += ["With 12 stressed and 4 control pod-runs the intervals are wide by construction. In the simulator the image features carry "
          "the response (growth, colour) while the response-type environment channels (water use, CO2 drawdown) are weak; "
          "whether that holds for real plants is exactly what Study D is meant to test.", ""]

    # ---------------------------------------------------------------- 9. twin calibration + RQ3 comparison
    allo_fn, a, b = F.fit_allometry(harvest_tab["projected_area_cm2"], harvest_tab["shoot_dry_mass"])
    ut = unit_tab.copy()
    final_u = units.rename(columns={"value": "dw_T"})
    final_u["unit_id"] = final_u["run"] + "-P" + final_u["pod"].astype(int).map("{:02d}".format)
    rows = []
    t0s = (3, 6, 9) if QUICK else (7, 14, 21)
    for t0 in t0s:
        d = ut[ut.day == t0].merge(final_u[["unit_id", "dw_T"]], on="unit_id")
        d["t0"], d["horizon"] = t0, DAYS - t0
        d["dw_t0"] = allo_fn(d["projected_area_cm2"])
        for k, v in (("ppfd_future", "ppfd"), ("t_day_future", "air_t_day"), ("t_night_future", "air_t_night"), ("ec_future", "ec")):
            d[k] = d["treatment"].map(lambda c: TREATMENTS[c]["recipe"][v])
        d["photoperiod_future"] = 16.0
        # before onset the future recipe is a schedule (control until onset, then treatment): use the time-weighted mean as the planned input
        w = np.clip((ONSET - t0) / (DAYS - t0), 0, 1)
        for k, v in (("ppfd_future", 250.0), ("t_day_future", 23.0), ("t_night_future", 20.0), ("ec_future", 1.4)):
            d[k] = w * v + (1 - w) * d[k]
        rows.append(d)
    ft = pd.concat(rows, ignore_index=True)
    models = {"mechanistic": lambda: MechanisticModel(), "ml_ridge": lambda: MLModel("ridge"), "ml_gbm": lambda: MLModel("gbm"), "hybrid": lambda: HybridModel("gbm")}
    pred = ft[["experiment_id", "unit_id", "treatment", "t0", "dw_T"]].copy()
    for name, mk in models.items():
        pred[name] = np.nan
        for run in sorted(ft.experiment_id.unique()):
            tr_, te_ = ft[ft.experiment_id != run], ft[ft.experiment_id == run]
            pred.loc[te_.index, name] = mk().fit(tr_).predict(te_)
    rq3 = []
    for name in models:
        for t0, g in pred.groupby("t0"):
            m = M.regression_metrics(g.dw_T, g[name])
            rq3.append({"model": name, "forecast_day": t0, "n_units": len(g), "mape": m["mape"], "rmse_g": m["rmse"], "bias_g": m["bias"]})
    rq3 = pd.DataFrame(rq3).pivot_table(index="model", columns="forecast_day", values="mape").reset_index()
    rq3.columns = [c if isinstance(c, str) else f"MAPE % @ day {c}" for c in rq3.columns]
    diffs = []
    for other in ("mechanistic", "ml_gbm"):
        dd = cluster_bootstrap_diff(pred["hybrid"] - pred.dw_T, pred[other] - pred.dw_T, pred["unit_id"], n_boot=4000)
        diffs.append({"comparison": f"hybrid - {other} (mean |error|, g)", **dd})
    S += ["## 8. RQ3 rehearsal - mechanistic vs ML vs hybrid forecast of harvest dry mass (leave-one-run-out, unit level)", "",
          f"Dry mass at the forecast day is taken from vision through an allometric fit on destructive samples (dw = {a:.4f} x area^{b:.2f}).", "",
          md_table(rq3), "", md_table(pd.DataFrame(diffs)), "",
          "Negative difference = hybrid better. The simulator's truth is the same model family as the mechanistic twin with shifted "
          "parameters, so this comparison is favourable to the physics-based models and cannot be read as evidence for RQ3.", ""]

    # twin parameter recovery on control units of the first three runs
    series = []
    for unit, g in ut[(ut.treatment == "C")].groupby("unit_id"):
        fin = final_u[final_u.unit_id == unit]
        la = harvest_tab[(harvest_tab.unit_id == unit) & (harvest_tab.day_harvest == DAYS)]["leaf_area"].mean()
        obs = pd.DataFrame({"day": [DAYS], "shoot_dw_g": [float(fin.dw_T.iloc[0])], "leaf_area_cm2": [la]})
        ser_h = harvest_tab[(harvest_tab.unit_id == unit) & (harvest_tab.day_harvest < DAYS)]
        obs = pd.concat([obs, pd.DataFrame({"day": ser_h.day_harvest.astype(int) + 0, "shoot_dw_g": ser_h.shoot_dry_mass, "leaf_area_cm2": ser_h.leaf_area})]).sort_values("day")
        obs = obs[obs.day >= 1]
        e = daily_env[daily_env.unit_id == unit].sort_values("day").iloc[:DAYS]
        series.append(cal.Series(unit, e.ppfd_light.fillna(250).to_numpy(), e.photoperiod_h.to_numpy(), e.air_t_light.fillna(23).to_numpy(),
                                 e.air_t_dark.to_numpy(), obs, co2=float(e.co2_light.mean()), ec=1.4))
    fit = cal.fit(series)
    rec = pd.DataFrame([{"parameter": k, "twin_default": getattr(cropm.CropParams(), k), "estimate": v, "se": fit["se"][k],
                         "simulator_truth": {"c_eps": 15.3e-6, "c_gr_max": 5.6e-6, "sla_obs": 0.032}[k]} for k, v in fit["estimates"].items()])
    S += ["## 9. Twin calibration (parameter recovery)", "",
          f"Fitted on the {len(series)} control pod-runs (serial + final harvest dry mass and leaf area); log-RMSE {fit['rmse_log']:.3f}:", "",
          md_table(rec, "{:.4g}"), "",
          "The estimates should move from the twin defaults towards the simulator's hidden values; unit and run random effects "
          "(which the fit absorbs into the parameters) prevent exact recovery. `c_eps` and `c_gr_max` are partly confounded.", ""]

    # ---------------------------------------------------------------- 10. dataset export
    ds = export_dataset(db, store, exps, OUT / "export", "0.0.1-sim", include_images=False)
    problems = verify_dataset(ds)
    S += ["## 10. Dataset export", "",
          f"Bundle `{ds.name}`: {sum(1 for _ in ds.rglob('*') if _.is_file())} files, manifest verification: "
          f"{'intact' if not problems else problems}. The bundle README carries the simulated-data warning.", "",
          f"Total runtime {time.time() - t_start:.0f} s.", ""]
    db.close()
    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text("\n".join(S))
    print("report:", REPORT)


if __name__ == "__main__":
    main()
